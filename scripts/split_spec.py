"""Split docs/SPEC.md into one file per `## ` section under docs/spec/, plus INDEX.md (FIX.md §3a).

docs/SPEC.md stays the full source of truth; re-run this script after every SPEC change.
"""
import pathlib
import re

src = pathlib.Path("docs/SPEC.md").read_text(encoding="utf-8")
parts = re.split(r"(?m)^## ", src)
out = pathlib.Path("docs/spec")
out.mkdir(exist_ok=True)
(out / "00-overview.md").write_text(parts[0], encoding="utf-8")
rows = ["| File | Section | ~tokens |", "| --- | --- | --- |"]
for i, p in enumerate(parts[1:], 1):
    title = p.splitlines()[0].replace("· New", "").replace("· Updated", "").strip()
    slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")[:48]
    name = f"{i:02d}-{slug}.md"
    (out / name).write_text("## " + p, encoding="utf-8")
    rows.append(f"| {name} | {title} | {len(p)//4} |")
(out / "INDEX.md").write_text(
    "# SPEC sections\n\nGenerated by `python scripts/split_spec.py` from docs/SPEC.md (the full source). "
    "Do not edit these files by hand.\n\n" + "\n".join(rows) + "\n",
    encoding="utf-8",
)
print("\n".join(rows))

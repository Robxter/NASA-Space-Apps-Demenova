// Builds severe-moment-data.js from the committed demo snapshot (synthetic demo farm, origin "synthetic").
// Run from the repo root: node design/prototypes/build-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const farm = JSON.parse(readFileSync('app/public/data/demo/farm.json', 'utf8'));
const day = (d) => JSON.parse(readFileSync(`app/public/data/demo/replay/${d}.json`, 'utf8'));
const before = day('2026-02-06');
const after = day('2026-02-07');
const level = (j, id) => j.units.find((u) => u.unit_id === id)?.alert?.level ?? null;

const pts = farm.lots.flatMap((l) => l.geometry.coordinates[0]);
const minX = Math.min(...pts.map((p) => p[0]));
const maxX = Math.max(...pts.map((p) => p[0]));
const minY = Math.min(...pts.map((p) => p[1]));
const maxY = Math.max(...pts.map((p) => p[1]));
const W = 300;
const pad = 30;
const scale = (W - 2 * pad) / (maxX - minX);
const H = Math.round((maxY - minY) * scale + 2 * pad);
const proj = ([x, y]) => [+((x - minX) * scale + pad).toFixed(1), +((maxY - y) * scale + pad).toFixed(1)];

const lots = farm.lots.map((l) => {
  const ring = l.geometry.coordinates[0].map(proj);
  const cx = ring.slice(0, -1).reduce((s, p) => s + p[0], 0) / (ring.length - 1);
  const cy = ring.slice(0, -1).reduce((s, p) => s + p[1], 0) / (ring.length - 1);
  return {
    id: l.id,
    name: l.name,
    d: `M${ring.map((p) => p.join(' ')).join('L')}Z`,
    cx: +cx.toFixed(1),
    cy: +cy.toFixed(1),
    before: level(before, l.id),
    after: level(after, l.id),
  };
});

const out = `// Generated by build-data.mjs from app/public/data/demo (synthetic demo farm). Do not edit.
// Levels: replay ${before.date} (before) and ${after.date} (after). Outlines projected linearly from EPSG:4326.
// Classic script (not a module) so the prototype opens from file:// without a server.
window.DN_PROTO = {
  view: { width: ${W}, height: ${H} },
  days: { before: '${before.date}', after: '${after.date}' },
  lots: ${JSON.stringify(lots)},
};
`;
writeFileSync('design/prototypes/severe-moment-data.js', out);
console.log(`${lots.length} lots, view ${W}x${H}; changes: ${lots.filter((l) => l.before !== l.after).map((l) => l.name).join(', ')}`);
